/**
 * Knowledge base of fraud schemes common in Kyrgyzstan and Central Asia.
 *
 * Sources to keep this list current: public warnings of the National Bank of the
 * Kyrgyz Republic (nbkr.kg), the Ministry of Internal Affairs (mvd.gov.kg) and
 * news coverage (24.kg, economist.kg, kaktus.media). Patterns are matched on
 * lower-cased text with "ё" replaced by "е". JavaScript's \b does not work with
 * Cyrillic, so patterns use word stems instead.
 */

/**
 * The four steps of a typical manipulation (social engineering):
 * trust — pose as someone you trust; bait — scare you or promise a gain;
 * urgency — rush you or demand secrecy; action — make you pay, share a code or open a link/file.
 */
export type Stage = "trust" | "bait" | "urgency" | "action";

export interface Pattern {
  re: RegExp;
  weight: number;
  /** Red flag shown to the user when this pattern matches. */
  label: string;
  stage: Stage;
  /** Feature tag used to explain what is missing and what to verify. */
  tag?: SignalTag;
}

/** Features the explanation layer reacts to (see explain.ts). */
export type SignalTag = "personal_data" | "referral" | "authority" | "urgency" | "opportunity" | "unverified_org" | "legit_channel";

export interface Scheme {
  id: string;
  name: string;
  /** What is true in reality, in one sentence. Shown as «На самом деле…». */
  reality: string;
  /** One-line description of how the scheme works. */
  howItWorks: string;
  patterns: Pattern[];
  advice: string[];
}

/**
 * In JavaScript `\w` only matches ASCII, so patterns are written with `\w` for
 * readability and rewritten here to match Cyrillic and Kyrgyz letters (ң, ө, ү).
 */
const p = (re: RegExp, weight: number, label: string, stage: Stage, tag?: SignalTag): Pattern => ({
  re: new RegExp(re.source.replace(/\\w/g, "[\\p{L}\\p{N}_]").replace(/\\W/g, "[^\\p{L}\\p{N}_]"), "u"),
  weight,
  label,
  stage,
  tag,
});

