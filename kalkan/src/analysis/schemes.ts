/**
 * Knowledge base of fraud schemes common in Kyrgyzstan and Central Asia.
 *
 * Sources to keep this list current: public warnings of the National Bank of the
 * Kyrgyz Republic (nbkr.kg), the Ministry of Internal Affairs (mvd.gov.kg) and
 * news coverage (24.kg, economist.kg, kaktus.media). Patterns are matched on
 * lower-cased text with "ё" replaced by "е". JavaScript's \b does not work with
 * Cyrillic, so patterns use word stems instead.
 */

export interface Pattern {
  re: RegExp;
  weight: number;
  /** Red flag shown to the user when this pattern matches. */
  label: string;
}

export interface Scheme {
  id: string;
  name: string;
  /** One-line description of how the scheme works. */
  howItWorks: string;
  patterns: Pattern[];
  advice: string[];
}

/**
 * In JavaScript `\w` only matches ASCII, so patterns are written with `\w` for
 * readability and rewritten here to match Cyrillic and Kyrgyz letters (ң, ө, ү).
 */
const p = (re: RegExp, weight: number, label: string): Pattern => ({
  re: new RegExp(re.source.replace(/\\w/g, "[\\p{L}\\p{N}_]").replace(/\\W/g, "[^\\p{L}\\p{N}_]"), "u"),
  weight,
  label,
});

