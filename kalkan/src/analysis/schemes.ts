export const SCHEME_BY_ID = new Map(SCHEMES.map((s) => [s.id, s]));

export function schemeName(id: string): string | undefined {
  return SCHEME_BY_ID.get(id)?.name;
}

/** Compact catalogue used in the AI system prompt. */
export function schemesCatalogue(): string {
  return SCHEMES.map((s) => `- ${s.id}: ${s.name}. ${s.howItWorks}`).join("\n");
}
